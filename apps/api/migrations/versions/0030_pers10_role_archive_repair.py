def _execute(statement: str, parameters: Mapping[str, object] | None = None) -> None:
    op.get_bind().execute(sa.text(statement), dict(parameters or {}))


def _role_exists(role: str) -> bool:
    return bool(
        op.get_bind()
        .execute(
            sa.text("SELECT EXISTS(SELECT 1 FROM pg_roles WHERE rolname=:role)"),
            {"role": role},
        )
        .scalar_one()
    )


def _assert_no_external_role_dependencies() -> None:
    external_count = (
        op.get_bind()
        .execute(
            sa.text(
                """
            SELECT count(*)
              FROM pg_shdepend dependency
              JOIN pg_roles role_row ON role_row.oid=dependency.refobjid
             WHERE role_row.rolname=:role
               AND dependency.dbid<>0
               AND dependency.dbid<>(
                 SELECT oid FROM pg_database WHERE datname=current_database()
               )
            """
            ),
            {"role": SOURCE_WRITER_ROLE},
        )
        .scalar_one()
    )
    if external_count:
        raise RuntimeError("PERS10_ROLE_EXTERNAL_DEPENDENCIES")


def _disable_archive_guards() -> None:
    for relation in (
        "legacy_governance_archive_record",
        "legacy_governance_archive_manifest",
    ):
        _execute(
            f"ALTER TABLE {ARCHIVE_SCHEMA}.{relation} DISABLE TRIGGER trg_pers10_archive_read_only"
        )


def _enable_archive_guards() -> None:
    for relation in (
        "legacy_governance_archive_record",
        "legacy_governance_archive_manifest",
    ):
        _execute(
            f"ALTER TABLE {ARCHIVE_SCHEMA}.{relation} ENABLE TRIGGER trg_pers10_archive_read_only"
        )


def _verify_row_hashes() -> None:
    mismatch = (
        op.get_bind()
        .execute(
            sa.text(
                f"""
            SELECT EXISTS(
              SELECT 1 FROM {ARCHIVE_SCHEMA}.legacy_governance_archive_record r
               WHERE r.row_sha256 <> encode(digest(convert_to(jsonb_build_object(
                 'entity_type',r.entity_type,'original_id',r.original_id,
                 'source_id',r.source_id,'payload',r.normalized_payload
               )::text,'UTF8'),'sha256'),'hex')
            )
            """
            )
        )
        .scalar_one()
    )
    if mismatch:
        raise RuntimeError("PERS10_ROLE_ARCHIVE_HASH_MISMATCH")


def _verify_manifests(*, complete_role_archive: bool) -> None:
    mismatch = (
        op.get_bind()
        .execute(
            sa.text(
                f"""
            SELECT EXISTS(
              SELECT 1 FROM {ARCHIVE_SCHEMA}.legacy_governance_archive_manifest m
              LEFT JOIN LATERAL(
                SELECT count(*) AS actual_count,
                       encode(digest(convert_to(
                         count(*)::text || E'\n' || COALESCE(string_agg(
                           r.original_id || ':' || r.row_sha256,E'\n'
                           ORDER BY r.original_id
                         ),''),'UTF8'),'sha256'),'hex') AS actual_hash
                  FROM {ARCHIVE_SCHEMA}.legacy_governance_archive_record r
                 WHERE r.entity_type=m.entity_type
              ) actual ON true
             WHERE m.original_count<>m.archive_count
                OR m.archive_count<>actual.actual_count
                OR m.aggregate_sha256<>actual.actual_hash
                OR (m.entity_type<>:entity AND
                    m.migration_version<>'0029_legacy_governance_retirement')
                OR (m.entity_type=:entity AND m.migration_version<>:role_version)
            )
            """
            ),
            {
                "entity": ENTITY_TYPE,
                "role_version": (
                    revision if complete_role_archive else "0029_legacy_governance_retirement"
                ),
            },
        )
        .scalar_one()
    )
    if mismatch:
        raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")


def _validate_payload(role: str, payload: Mapping[str, object]) -> None:
    if (
        payload.get("rolname") != role
        or payload.get("rolinherit") is not True
        or not isinstance(payload.get("rolconnlimit"), int)
        or int(payload["rolconnlimit"]) < -1
    ):
        raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")
    memberships = payload.get("memberships")
    grants = payload.get("table_privileges")
    if not isinstance(memberships, list) or not isinstance(grants, list):
        raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")
    for membership in memberships:
        if (
            not isinstance(membership, dict)
            or not isinstance(membership.get("role"), str)
            or not isinstance(membership.get("admin_option"), bool)
            or membership["role"] in PERS10_ROLES
        ):
            raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")
    for grant in grants:
        if (
            not isinstance(grant, dict)
            or grant.get("schema") not in {"public", ARCHIVE_SCHEMA}
            or not isinstance(grant.get("relation"), str)
            or grant.get("privilege") not in ALLOWED_PRIVILEGES
            or not isinstance(grant.get("grantable"), bool)
        ):
            raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")


def _role_payloads() -> dict[str, Mapping[str, object]]:
    payloads = {
        row[0]: row[1]
        for row in op.get_bind().execute(
            sa.text(
                f"SELECT original_id,normalized_payload FROM {ARCHIVE_SCHEMA}."
                "legacy_governance_archive_record WHERE entity_type=:entity"
            ),
            {"entity": ENTITY_TYPE},
        )
    }
    for role, payload in payloads.items():
        if role not in PERS10_ROLES or not isinstance(payload, dict):
            raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")
        _validate_payload(role, payload)
    return payloads


def _verify_pre_repair_archive() -> dict[str, Mapping[str, object]]:
    _verify_row_hashes()
    payloads = _role_payloads()
    if set(payloads) not in (set(), set(PERS10_0029_ROLES)):
        raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")
    manifest_count = (
        op.get_bind()
        .execute(
            sa.text(
                f"SELECT count(*) FROM {ARCHIVE_SCHEMA}.legacy_governance_archive_manifest "
                "WHERE entity_type=:entity"
            ),
            {"entity": ENTITY_TYPE},
        )
        .scalar_one()
    )
    if manifest_count != (1 if payloads else 0):
        raise RuntimeError("PERS10_ROLE_ARCHIVE_COUNT_MISMATCH")
    _verify_manifests(complete_role_archive=False)
    for role in PERS10_0029_ROLES:
        if _role_exists(role):
            raise RuntimeError("PERS10_ROLE_STATE_UNEXPECTED")
    if not _role_exists(SOURCE_WRITER_ROLE):
        raise RuntimeError("PERS10_ROLE_STATE_UNEXPECTED")
    return payloads


def _capture_source_writer_payload() -> Mapping[str, object]:
    payload = (
        op.get_bind()
        .execute(
            sa.text(
                """
            SELECT jsonb_build_object(
              'rolname',role_row.rolname,
              'rolinherit',role_row.rolinherit,
              'rolconnlimit',role_row.rolconnlimit,
              'memberships',COALESCE((
                SELECT jsonb_agg(jsonb_build_object(
                  'role',parent.rolname,'admin_option',membership.admin_option
                ) ORDER BY parent.rolname)
                  FROM pg_auth_members membership
                  JOIN pg_roles parent ON parent.oid=membership.roleid
                 WHERE membership.member=role_row.oid
              ),'[]'::jsonb),
              'table_privileges',COALESCE((
                SELECT jsonb_agg(jsonb_build_object(
                  'schema',grant_row.table_schema,'relation',grant_row.table_name,
                  'privilege',grant_row.privilege_type,
                  'grantable',grant_row.is_grantable='YES'
                ) ORDER BY grant_row.table_schema,grant_row.table_name,
                           grant_row.privilege_type)
                  FROM information_schema.role_table_grants grant_row
                 WHERE grant_row.grantee=role_row.rolname
              ),'[]'::jsonb)
            )
              FROM pg_roles role_row WHERE role_row.rolname=:role
            """
            ),
            {"role": SOURCE_WRITER_ROLE},
        )
        .scalar_one_or_none()
    )
    if not isinstance(payload, dict):
        raise RuntimeError("PERS10_ROLE_STATE_UNEXPECTED")
    _validate_payload(SOURCE_WRITER_ROLE, payload)
    return payload


def _insert_role_record(role: str, payload: Mapping[str, object], archived_at: object) -> None:
    _execute(
        f"""
        INSERT INTO {ARCHIVE_SCHEMA}.legacy_governance_archive_record(
          entity_type,original_id,source_id,normalized_payload,row_sha256,archived_at
        ) VALUES(
          :entity,:role,NULL::uuid,CAST(:payload AS jsonb),
          encode(digest(convert_to(jsonb_build_object(
            'entity_type',CAST(:entity AS text),'original_id',CAST(:role AS text),
            'source_id',NULL::uuid,'payload',CAST(:payload AS jsonb)
          )::text,'UTF8'),'sha256'),'hex'),CAST(:archived_at AS timestamptz)
        )
        """,
        {
            "entity": ENTITY_TYPE,
            "role": role,
            "payload": json.dumps(payload, sort_keys=True, separators=(",", ":")),
            "archived_at": archived_at,
        },
    )


def _write_role_manifest(*, count: int, migration_version: str, archived_at: object) -> None:
    archive_count, aggregate = (
        op.get_bind()
        .execute(
            sa.text(
                f"""
            SELECT count(*),encode(digest(convert_to(
              count(*)::text || E'\n' || COALESCE(string_agg(
                original_id || ':' || row_sha256,E'\n' ORDER BY original_id
              ),''),'UTF8'),'sha256'),'hex')
              FROM {ARCHIVE_SCHEMA}.legacy_governance_archive_record
             WHERE entity_type=:entity
            """
            ),
            {"entity": ENTITY_TYPE},
        )
        .one()
    )
    if archive_count != count:
        raise RuntimeError("PERS10_ROLE_ARCHIVE_COUNT_MISMATCH")
    _execute(
        f"""
        INSERT INTO {ARCHIVE_SCHEMA}.legacy_governance_archive_manifest(
          entity_type,source_relation,original_count,archive_count,
          aggregate_sha256,migration_version,archived_at
        ) VALUES(:entity,:source_relation,:count,:count,:aggregate,:version,:archived_at)
        """,
        {
            "entity": ENTITY_TYPE,
            "source_relation": "pg_roles@0028+0029-role-repair",
            "count": count,
            "aggregate": aggregate,
            "version": migration_version,
            "archived_at": archived_at,
        },
    )


def _verify_complete_role_archive(*, require_roles_absent: bool = True) -> None:
    _verify_row_hashes()
    payloads = _role_payloads()
    if set(payloads) != set(PERS10_ROLES):
        raise RuntimeError("PERS10_ROLE_ARCHIVE_COUNT_MISMATCH")
    _verify_manifests(complete_role_archive=True)
    if require_roles_absent:
        for role in PERS10_ROLES:
            if _role_exists(role):
                raise RuntimeError("PERS10_ROLE_STATE_UNEXPECTED")


def _restore_source_governance_writer() -> None:
    payload = _role_payloads().get(SOURCE_WRITER_ROLE)
    if payload is None:
        raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")
    bind = op.get_bind()
    quote = bind.dialect.identifier_preparer.quote
    connection_limit = int(payload["rolconnlimit"])
    _execute(
        f"CREATE ROLE {quote(SOURCE_WRITER_ROLE)} NOLOGIN INHERIT NOSUPERUSER "
        "NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS "
        f"CONNECTION LIMIT {connection_limit}"
    )
    for membership in payload["memberships"]:
        parent = str(membership["role"])
        if not _role_exists(parent):
            raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")
        suffix = " WITH ADMIN OPTION" if membership["admin_option"] is True else ""
        _execute(f"GRANT {quote(parent)} TO {quote(SOURCE_WRITER_ROLE)}{suffix}")
    for grant in payload["table_privileges"]:
        schema = str(grant["schema"])
        relation = str(grant["relation"])
        privilege = str(grant["privilege"])
        exists = (
            op.get_bind()
            .execute(
                sa.text("SELECT to_regclass(:name) IS NOT NULL"),
                {"name": f"{schema}.{relation}"},
            )
            .scalar_one()
        )
        if not exists:
            raise RuntimeError("PERS10_ROLE_ARCHIVE_CORRUPT")
        suffix = " WITH GRANT OPTION" if grant["grantable"] is True else ""
        _execute(
            f"GRANT {privilege} ON TABLE {quote(schema)}.{quote(relation)} "
            f"TO {quote(SOURCE_WRITER_ROLE)}{suffix}"
        )


def _restore_0029_role_manifest() -> None:
    archived_at = op.get_bind().execute(sa.text("SELECT transaction_timestamp()")).scalar_one()
    _disable_archive_guards()
    _execute(
        f"DELETE FROM {ARCHIVE_SCHEMA}.legacy_governance_archive_record "
        "WHERE entity_type=:entity AND original_id=:role",
        {"entity": ENTITY_TYPE, "role": SOURCE_WRITER_ROLE},
    )
    _execute(
        f"DELETE FROM {ARCHIVE_SCHEMA}.legacy_governance_archive_manifest "
        "WHERE entity_type=:entity",
        {"entity": ENTITY_TYPE},
    )
    _write_role_manifest(
        count=2,
        migration_version="0029_legacy_governance_retirement",
        archived_at=archived_at,
    )
    _enable_archive_guards()


def upgrade() -> None:
    _execute("SET LOCAL TIME ZONE 'UTC'")
    _assert_no_external_role_dependencies()
    existing_payloads = _verify_pre_repair_archive()
    source_payload = _capture_source_writer_payload()
    archived_at = op.get_bind().execute(sa.text("SELECT transaction_timestamp()")).scalar_one()
    _disable_archive_guards()
    _execute(
        f"DELETE FROM {ARCHIVE_SCHEMA}.legacy_governance_archive_manifest "
        "WHERE entity_type=:entity",
        {"entity": ENTITY_TYPE},
    )
    if not existing_payloads:
        for role in PERS10_0029_ROLES:
            _insert_role_record(role, RECONSTRUCTED_0028_PAYLOADS[role], archived_at)
    _insert_role_record(SOURCE_WRITER_ROLE, source_payload, archived_at)
    _write_role_manifest(count=3, migration_version=revision, archived_at=archived_at)
    _enable_archive_guards()
    _verify_complete_role_archive(require_roles_absent=False)
    _execute(f"DROP OWNED BY {SOURCE_WRITER_ROLE}")
    _execute(f"DROP ROLE {SOURCE_WRITER_ROLE}")
    if _role_exists(SOURCE_WRITER_ROLE):
        raise RuntimeError("PERS10_ROLE_STATE_UNEXPECTED")


def downgrade() -> None:
    _verify_complete_role_archive()
    _restore_source_governance_writer()
    _restore_0029_role_manifest()
