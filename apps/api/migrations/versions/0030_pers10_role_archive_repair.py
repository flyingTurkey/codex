ARCHIVE_SCHEMA = "legacy_governance_archive"
ENTITY_TYPE = "database_role"
SOURCE_WRITER_ROLE = "srbg_source_governance_writer"
PERS10_ROLES: tuple[str, ...] = (
    "srbg_admin_role",
    "srbg_model_role",
    SOURCE_WRITER_ROLE,
)
PERS10_0029_ROLES: tuple[str, ...] = ("srbg_admin_role", "srbg_model_role")
ALLOWED_PRIVILEGES = {
    "SELECT",
    "INSERT",
    "UPDATE",
    "DELETE",
    "TRUNCATE",
    "REFERENCES",
    "TRIGGER",
}

